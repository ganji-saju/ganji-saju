// ─── 십성 조합 설명에 오행을 섞는다(2026-09-27) ───────────────────────────────
//   같은 '식상'이라도 태어난 날 오행에 따라 실제 기운이 다르다(목 일간의 식상 = 화 기운).
const CYCLE: El[] = ['목', '화', '토', '금', '수'];
const GROUP_STEP: Record<string, number> = { 비겁: 0, 식상: 1, 재성: 2, 관성: 3, 인성: 4 };

/** 일간 오행 기준으로 십성 묶음의 오행. */
export function tenGodGroupElement(dayElement: El, group: keyof typeof GROUP_STEP): El {
  return CYCLE[(CYCLE.indexOf(dayElement) + GROUP_STEP[group]) % 5];
}

/** 문단에서 처음 나오는 십성 묶음 이름마다 '(X 기운)'을 붙인다. */
export function annotateTenGodGroups(text: string, dayElement: El) {
  const done = new Set<string>();
  return text.replace(/비겁|식상|재성|관성|인성/g, (group) => {
    if (done.has(group)) return group;
    done.add(group);
    return `${group}(${tenGodGroupElement(dayElement, group as keyof typeof GROUP_STEP)} 기운)`;
  });
}

