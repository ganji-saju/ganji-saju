  겁재: { meaning: '경쟁과 공동의 몫', work: '여러 사람의 이해관계를 조율하되 본인 몫도 분명한 역할', scene: '함께 시작한 일에서 누가 결정하고 누가 마무리할지 나누는 일', bond: '같이하는 즐거움과 서로 거절할 권리를 함께 지키는 관계' },
  식신: { meaning: '꾸준한 생산과 표현', work: '직접 만든 결과를 반복해서 개선하는 역할', scene: '한 번의 화려한 발표보다 매번 일정한 품질로 결과를 전달하는 일', bond: '말로 크게 약속하기보다 작은 행동과 시간을 꾸준히 쌓는 관계' },
