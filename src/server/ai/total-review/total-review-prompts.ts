export function buildRetryCorrectionNote(reasons: readonly string[]): string {
  if (reasons.length === 0) return '';
  return [
    '## 재작성 지시 — 직전 출력이 아래 규칙을 어겨 폐기되었습니다',
    ...reasons.map((reason) => `- ${reason}`),
    '',
    '지적된 항목만 고쳐 같은 JSON 형식으로 다시 출력하세요. 지적되지 않은 부분의 내용과 톤은 유지합니다.',
  ].join('\n');
}

export function buildSectionUserMessage(
  sectionId: TotalReviewSectionId,
  input: TotalReviewInput
): string {
  const lines: string[] = [];
  if (sectionId === 'main_narrative') {
    lines.push(MAIN_NARRATIVE_FEW_SHOT, '');
  }
  lines.push(
    SECTION_INSTRUCTIONS[sectionId],
    '',
    '## 입력 JSON',
    JSON.stringify(input, null, 2)
  );
  return lines.join('\n');
}
